-- As tabelas abaixo são acessadas pelo backend confiável, não diretamente pelo navegador.
-- Por isso RLS fica habilitado e sem políticas públicas permissivas.
alter table public.users enable row level security;
alter table public.carts enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.tickets enable row level security;
alter table public.ticket_messages enable row level security;
alter table public.logs enable row level security;
alter table public.pix_orders enable row level security;
alter table public.pix_orders_event_guard enable row level security;
alter table public.chat_messages enable row level security;
alter table public.site_settings enable row level security;
alter table public.reviews enable row level security;

-- Storage: leitura pública para as imagens publicadas.
drop policy if exists "kaneki assets public read" on storage.objects;
create policy "kaneki assets public read"
on storage.objects for select
using (bucket_id='kaneki-assets');

-- Upload/alteração/exclusão são feitos pelo backend com a service role.
-- A service role não deve ser colocada no HTML/JavaScript do navegador.

-- Índices úteis.
create index if not exists products_catalog_active_idx on public.products(catalog,active);
create index if not exists orders_user_idx on public.orders(user_id,created_at desc);
create index if not exists tickets_user_idx on public.tickets(user_id,updated_at desc);
create index if not exists chat_created_idx on public.chat_messages(created_at desc);
create index if not exists logs_at_idx on public.logs(at desc);

-- Recarrega o cache do PostgREST depois da criação das estruturas.
