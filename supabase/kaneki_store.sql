-- KANEKI STORE + SUPABASE
-- Execute este arquivo inteiro no Supabase Dashboard > SQL Editor.
-- O backend da KANEKI usa a conexão PostgreSQL do Supabase e faz as operações administrativas no servidor.

create extension if not exists pgcrypto;

create table if not exists public.users (
  id text primary key,
  email text unique not null,
  name text not null,
  phone text default '',
  password_hash text,
  role text not null default 'customer' check (role in ('customer','admin','owner')),
  provider text not null default 'password',
  avatar_url text default '',
  created_at timestamptz not null default now()
);

create table if not exists public.carts (
  user_id text primary key references public.users(id) on delete cascade,
  cart jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  product_id text primary key,
  name text not null,
  description text not null default '',
  price numeric not null,
  old_price numeric not null default 0,
  stock text not null default '0',
  image text not null default '',
  catalog text not null default 'produtos',
  active boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id text references public.users(id) on delete set null,
  order_key text unique not null,
  items jsonb not null,
  total numeric not null,
  name text,
  email text,
  phone text,
  status text not null default 'pending',
  created_at timestamptz not null default now()
);

create table if not exists public.tickets (
  id bigint generated by default as identity primary key,
  user_id text references public.users(id) on delete cascade,
  order_id bigint references public.orders(id) on delete cascade,
  subject text not null,
  status text not null default 'open',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ticket_messages (
  id bigint generated by default as identity primary key,
  ticket_id bigint references public.tickets(id) on delete cascade,
  sender_role text not null,
  name text not null,
  message text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.logs (
  id bigint generated by default as identity primary key,
  action text not null,
  email text,
  at timestamptz not null default now()
);

create table if not exists public.pix_orders (
  id bigint generated by default as identity primary key,
  order_id bigint references public.orders(id) on delete set null,
  order_key text unique not null,
  qr_code_id text unique not null,
  amount numeric not null,
  status text not null default 'PENDING',
  nick text default '',
  expires_at timestamptz,
  asaas_payment_id text,
  event_id text unique,
  created_at timestamptz not null default now(),
  paid_at timestamptz
);

create table if not exists public.pix_orders_event_guard (
  event_id text primary key,
  received_at timestamptz not null default now()
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  user_id text references public.users(id) on delete set null,
  name text not null,
  message text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.site_settings (
  key text primary key,
  value text not null default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  user_id text references public.users(id) on delete set null,
  order_id bigint references public.orders(id) on delete set null,
  rating int not null check (rating between 1 and 5),
  message text not null,
  product_text text not null default '',
  created_at timestamptz not null default now(),
  unique(user_id,order_id)
);

